/// Two versions of one registry package: moving the one only core reaches
/// (`dup 2.0.0`) is not a change of the rust plugin, which reaches `dup 1.0.0`.
#[test]
fn moving_the_core_copy_of_a_package_in_two_versions_is_not_a_plugin_change() {
    let repo = Repo::tagged();
    repo.set_lock_version("dup", "2.0.0", "2.0.1");
    repo.replace("Cargo.lock", "\"dup 2.0.0\"", "\"dup 2.0.1\"");
    repo.commit_and_check().accepted();
}

/// The other half: moving the copy the rust plugin reaches is its change.
#[test]
fn moving_the_plugin_copy_of_a_package_in_two_versions_is_refused_for_that_plugin() {
    let repo = Repo::tagged();
    repo.set_lock_version("dup", "1.0.0", "1.0.1");
    repo.replace("Cargo.lock", "\"dup 1.0.0\"", "\"dup 1.0.1\"");
    let checked = repo.commit_and_check();
    checked.refused("rust", "Cargo.lock");
    checked.not_refused_for("python");
    checked.not_refused_for("typescript");
}

