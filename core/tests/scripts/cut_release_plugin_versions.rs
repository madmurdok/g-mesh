/// A plugin absent at the tag is new: it starts at any version.
#[test]
fn a_plugin_absent_at_the_tag_is_accepted() {
    let repo = Repo::committed();
    repo.git(&["rm", "-r", "-q", "plugins/typescript"]);
    repo.commit("drop typescript");
    repo.git(&["tag", TAG]);
    repo.git(&["checkout", "-q", "HEAD~1", "--", "plugins/typescript"]);
    repo.set_plugin_version("typescript", "0.1.0");
    repo.commit_and_check().accepted();
}

/// Behaviour 12, first half: with no `v*` tag the change rule is skipped,
/// so an unbumped source edit passes.
#[test]
fn without_a_v_tag_the_change_rule_is_skipped() {
    let repo = Repo::committed();
    repo.git(&["tag", "baseline"]);
    repo.touch("plugins/python/src/lib.rs");
    let checked = repo.commit_and_check();
    checked.accepted();
    assert!(checked.stdout().contains("skipping"), "the skip is logged\n{}", checked.report());
}

/// Behaviour 12, second half: rule (a) still holds without a tag.
