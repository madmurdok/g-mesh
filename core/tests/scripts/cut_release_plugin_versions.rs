fn script() -> PathBuf {
    match std::env::var_os("GM_CUT_RELEASE_SH") {
        Some(path) => PathBuf::from(path),
        None => Path::new(env!("CARGO_MANIFEST_DIR")).join("../scripts/cut-release.sh"),
    }
}

/// A command whose git reads no user or system config (signing, hooks,
/// default branch), so the scratch repo behaves the same on every machine.
fn isolated(program: &str) -> Command {
    let mut command = Command::new(program);
    command
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_AUTHOR_NAME", "test")
        .env("GIT_AUTHOR_EMAIL", "test@example.com")
        .env("GIT_COMMITTER_NAME", "test")
        .env("GIT_COMMITTER_EMAIL", "test@example.com");
    command
}

fn manifest(name: &str, extra: &str) -> String {
    format!("[package]\nname = \"{name}\"\nversion = \"1.0.0\"\nedition = \"2021\"\n{extra}")
}

struct Repo {
    dir: tempfile::TempDir,
}

impl Repo {
    /// The workspace shape at release 1.0.0, committed and tagged `v1.0.0`.
    fn tagged() -> Self {
        let repo = Self::committed();
        repo.git(&["tag", TAG]);
        repo
    }

    /// The same, committed but with no tag at all.
    fn committed() -> Self {
        let repo = Repo { dir: tempfile::tempdir().expect("failed to create a scratch repo") };
        repo.git(&["init", "-q", "-b", "main"]);
        repo.write("core/Cargo.toml", &manifest("g-mesh", ""));
        repo.write("plugins/sdk/Cargo.toml", &manifest("g-mesh-plugin-sdk", ""));
        repo.write("wire/Cargo.toml", &manifest("g-mesh-wire", ""));
        repo.write("walk/Cargo.toml", &manifest("g-mesh-walk", ""));
        for crate_dir in ["core", "plugins/sdk", "wire", "walk"] {
            repo.write(&format!("{crate_dir}/src/lib.rs"), "pub fn f() {}\n");
        }
        for plugin in PLUGINS {
            let dir = format!("plugins/{plugin}");
            repo.write(
                &format!("{dir}/Cargo.toml"),
                &manifest(
                    &format!("g-mesh-plugin-{plugin}"),
                    "\n[dependencies]\ng-mesh-plugin-sdk = { path = \"../sdk\" }\n",
                ),
            );
            repo.write(
                &format!("{dir}/plugin.toml"),
                &format!("[plugin]\nname = \"{plugin}\"\nplugin_version = \"1.0.0\"\n"),
            );
            repo.write(&format!("{dir}/src/lib.rs"), "pub fn f() {}\n");
            repo.write(&format!("{dir}/tests/smoke.rs"), "#[test]\nfn smoke() {}\n");
            repo.write(&format!("{dir}/README.md"), "# plugin\n");
        }
        repo.write("conformance/cases.txt", "one\n");
        repo.write("README.md", "# g-mesh\n");
        repo.write("Cargo.lock", LOCK);
        repo.commit("1.0.0");
        repo
    }

    fn path(&self) -> &Path {
        self.dir.path()
    }

    fn git(&self, args: &[&str]) {
        let output =
            isolated("git").arg("-C").arg(self.path()).args(args).output().expect("failed to run git");
        assert!(output.status.success(), "git {args:?} failed: {}", String::from_utf8_lossy(&output.stderr));
    }

    fn write(&self, relative: &str, text: &str) {
        let target = self.path().join(relative);
        fs::create_dir_all(target.parent().unwrap()).unwrap();
        fs::write(target, text).unwrap();
    }

    /// Replaces the one occurrence of `from` in `relative` with `to`.
    fn replace(&self, relative: &str, from: &str, to: &str) {
        let text = fs::read_to_string(self.path().join(relative)).unwrap();
        assert_eq!(text.matches(from).count(), 1, "expected one {from:?} in {relative}:\n{text}");
        self.write(relative, &text.replacen(from, to, 1));
    }

    /// Appends a line to a source or text file: a change that is not a
    /// version line.
    fn touch(&self, relative: &str) {
        let text = fs::read_to_string(self.path().join(relative)).unwrap();
        self.write(relative, &format!("{text}// edited\n"));
    }

    /// Sets the `[package] version` of the manifest at `relative`.
    fn set_crate_version(&self, relative: &str, version: &str) {
        self.replace(relative, "version = \"1.0.0\"", &format!("version = \"{version}\""));
    }

    fn set_plugin_toml_version(&self, plugin: &str, version: &str) {
        self.replace(
            &format!("plugins/{plugin}/plugin.toml"),
            "plugin_version = \"1.0.0\"",
            &format!("plugin_version = \"{version}\""),
        );
    }

    /// Moves a plugin to `version` in both of its manifests.
    fn set_plugin_version(&self, plugin: &str, version: &str) {
        self.set_crate_version(&format!("plugins/{plugin}/Cargo.toml"), version);
        self.set_plugin_toml_version(plugin, version);
    }

    /// Moves a package's `version` in Cargo.lock.
    fn set_lock_version(&self, name: &str, from: &str, to: &str) {
        self.replace(
            "Cargo.lock",
            &format!("name = \"{name}\"\nversion = \"{from}\""),
            &format!("name = \"{name}\"\nversion = \"{to}\""),
        );
    }

    fn commit(&self, message: &str) {
        self.git(&["add", "-A"]);
        self.git(&["commit", "-q", "--allow-empty", "-m", message]);
    }

    fn check(&self) -> Checked {
        let output = isolated("bash")
            .arg("-c")
            .arg(r#"source "$1" && REPO_ROOT="$2" && check_crate_backed_plugin_versions "$3""#)
            .arg("cut-release-test")
            .arg(script())
            .arg(self.path())
            .arg(RELEASE)
            .output()
            .expect("failed to run bash");
        Checked(output)
    }

    /// Commits the edits made so far and runs the check.
    fn commit_and_check(&self) -> Checked {
        self.commit("edit");
        self.check()
    }
}

struct Checked(Output);

impl Checked {
    fn stdout(&self) -> String {
        String::from_utf8_lossy(&self.0.stdout).into_owned()
    }

    fn stderr(&self) -> String {
        String::from_utf8_lossy(&self.0.stderr).into_owned()
    }

    fn report(&self) -> String {
        format!("status: {}\nstdout:\n{}\nstderr:\n{}", self.0.status, self.stdout(), self.stderr())
    }

    fn accepted(&self) {
        assert!(self.0.status.success(), "the check must accept\n{}", self.report());
    }

    /// The stderr lines that name plugins/<plugin>.
    fn lines_naming(&self, plugin: &str) -> Vec<String> {
        let named = [format!("plugins/{plugin} "), format!("plugins/{plugin}/")];
        self.stderr()
            .lines()
            .filter(|line| named.iter().any(|name| line.contains(name.as_str())))
            .map(str::to_owned)
            .collect()
    }

    /// Refused, with a line naming the plugin and `path`.
    fn refused(&self, plugin: &str, path: &str) {
        assert!(!self.0.status.success(), "the check must refuse\n{}", self.report());
        assert!(
            self.lines_naming(plugin).iter().any(|line| line.contains(path)),
            "a refusal must name plugins/{plugin} and {path}\n{}",
            self.report()
        );
    }

    fn not_refused_for(&self, plugin: &str) {
        assert!(
            self.lines_naming(plugin).is_empty(),
            "plugins/{plugin} must not be refused\n{}",
            self.report()
        );
    }
}

/// The release bump of the shared crates and core, and of their path entries
/// in Cargo.lock, is not a change of any plugin (behaviour 1).
#[test]
fn the_release_bump_of_core_and_the_shared_crates_changes_no_plugin() {
    let repo = Repo::tagged();
    for manifest in ["core/Cargo.toml", "plugins/sdk/Cargo.toml", "wire/Cargo.toml", "walk/Cargo.toml"] {
        repo.set_crate_version(manifest, RELEASE);
    }
    for name in ["g-mesh", "g-mesh-plugin-sdk", "g-mesh-wire", "g-mesh-walk"] {
        repo.set_lock_version(name, "1.0.0", RELEASE);
    }
    repo.commit_and_check().accepted();
}

/// Behaviour 2.
#[test]
fn a_plugin_source_edit_without_a_bump_is_refused_for_that_plugin_only() {
    let repo = Repo::tagged();
    repo.touch("plugins/python/src/lib.rs");
    let checked = repo.commit_and_check();
    checked.refused("python", "plugins/python/src/lib.rs");
    checked.not_refused_for("rust");
    checked.not_refused_for("typescript");
}

/// Behaviour 3.
#[test]
fn a_plugin_source_edit_with_a_bump_in_both_manifests_is_accepted() {
    let repo = Repo::tagged();
    repo.touch("plugins/python/src/lib.rs");
    repo.set_plugin_version("python", "1.0.1");
    repo.commit_and_check().accepted();
}

/// Behaviours 4 and 5: a shared crate's source is a shipped input of every
/// plugin.
fn a_shared_source_edit_is_refused_for_every_plugin(shared_crate: &str) {
    let repo = Repo::tagged();
    let path = format!("{shared_crate}/src/lib.rs");
    repo.touch(&path);
    let checked = repo.commit_and_check();
    for plugin in PLUGINS {
        checked.refused(plugin, &path);
    }
}

