package main

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
)

// The cases shared with the SDK detector (plugins/sdk/src/generated.rs reads
// the same file).
const sharedCasesPath = "../sdk/testdata/generated_headers.json"

type generatedCase struct {
	Name      string `json:"name"`
	Source    string `json:"source"`
	Generated bool   `json:"generated"`
}

func loadGeneratedCases(t *testing.T) []generatedCase {
	t.Helper()
	raw, err := os.ReadFile(filepath.FromSlash(sharedCasesPath))
	if err != nil {
		t.Fatalf("reading the shared case file: %v", err)
	}
	var file struct {
		Cases []generatedCase `json:"cases"`
	}
	if err := json.Unmarshal(raw, &file); err != nil {
		t.Fatalf("the shared case file is not JSON: %v", err)
	}
	return file.Cases
}

// Every shared case gets its verdict from isGenerated: the section 3 rules
// table, the false hits, the header-window cases and the review cases.
//
// Controls: headerLines' `default: return header` becoming `default:` (no
// stop at the first other line) fails "marker after the first code line";
// isGenerated using `line := raw` instead of `unquoted(raw)` fails "module
// doc quoting the markers in backticks".
func TestIsGeneratedAgreesWithEverySharedCase(t *testing.T) {
	cases := loadGeneratedCases(t)
	if len(cases) != 85 {
		t.Fatalf("the shared case file has %d cases, want 85; update this count with it", len(cases))
	}
	for _, c := range cases {
		if got := isGenerated([]byte(c.Source)); got != c.Generated {
			t.Errorf("%s: isGenerated = %v, want %v", c.Name, got, c.Generated)
		}
	}
}

const generatedGoFile = "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage pb\n\n// Get returns the value.\nfunc Get() int { return 1 }\n\ntype Msg struct{}\n"
const plainGoFile = "package pb\n\n// Get returns the value.\nfunc Get() int { return 1 }\n"

// Bulk index: every node of a marked file carries "generated":true and no
// node of an unmarked file carries the key at all.
//
// Control: drop `node.Generated = e.generated` in extractor.addNode (the
// declarations lose the flag).
func TestRunBulkIndexFlagsEveryNodeOfAGeneratedFile(t *testing.T) {
	root := t.TempDir()
	writeFile(t, root, "pb/msg.pb.go", generatedGoFile)
	writeFile(t, root, "app/app.go", plainGoFile)

	var out bytes.Buffer
	if _, err := runBulkIndex(root, &out); err != nil {
		t.Fatalf("runBulkIndex failed: %v", err)
	}
	perFile := map[string]int{}
	for _, line := range bytes.Split(bytes.TrimSpace(out.Bytes()), []byte("\n")) {
		var record map[string]json.RawMessage
		if err := json.Unmarshal(line, &record); err != nil {
			t.Fatalf("emitted line did not parse as JSON: %v\nline: %s", err, line)
		}
		if _, isFacts := record["resolutionFacts"]; isFacts {
			continue
		}
		if _, isEdge := record["fromId"]; isEdge {
			continue
		}
		var path string
		_ = json.Unmarshal(record["filePath"], &path)
		perFile[path]++
		flag, has := record["generated"]
		switch path {
		case "pb/msg.pb.go":
			if !has || string(flag) != "true" {
				t.Errorf("a node of the generated file lacks \"generated\":true: %s", line)
			}
		case "app/app.go":
			if has {
				t.Errorf("a node of an ordinary file carries the generated key: %s", line)
			}
		}
	}
	if perFile["pb/msg.pb.go"] < 3 || perFile["app/app.go"] < 2 {
		t.Fatalf("nodes per file = %v, want the File node plus declarations for both", perFile)
	}
}

// fileChanged: adding the marker to an indexed file re-sends every node with
// the flag set, and removing it re-sends them with the flag cleared.
//
// Control: nodesEqual ignoring Generated (`a.Generated = b.Generated` before
// the DeepEqual) answers an empty diff to the marker edit.
func TestHandleFileChangedFlipsTheGeneratedFlagBothWays(t *testing.T) {
	root := t.TempDir()
	plain := "package pb\n\n// Get returns the value.\nfunc Get() int { return 1 }\n"
	// The same declarations at the same lines: only the header differs.
	marked := "// Code generated by hand. DO NOT EDIT.\npackage pb\n// Get returns the value.\nfunc Get() int { return 1 }\n"
	writeFile(t, root, "a.go", plain)
	state := newPluginState(root)

	assertFlags := func(label string, diff fileChangeDiff, want bool) {
		t.Helper()
		if len(diff.UpsertNodes) < 2 {
			t.Fatalf("%s: %d node upserts, want the File node and Get re-sent: %+v", label, len(diff.UpsertNodes), diff)
		}
		for _, node := range diff.UpsertNodes {
			if node.Generated != want {
				t.Errorf("%s: node %s (%s) Generated = %v, want %v", label, node.Name, node.Kind, node.Generated, want)
			}
		}
	}

	assertFlags("first sight", state.handleFileChanged("a.go"), false)
	writeFile(t, root, "a.go", marked)
	assertFlags("marker added", state.handleFileChanged("a.go"), true)
	writeFile(t, root, "a.go", plain)
	assertFlags("marker removed", state.handleFileChanged("a.go"), false)
}
