package main

// Generated-file detection from a file's leading comment block.
//
// The rule is shared with the SDK (`plugins/sdk/src/generated.rs`), and both
// read the cases in `plugins/sdk/testdata/generated_headers.json`: a change
// here is made there too. Design: `docs/design/GM-646-skip-generated-files.md`
// section 3.

import (
	"strings"
	"unicode"
	"unicode/utf8"
)

const (
	// The header window: at most this many lines...
	maxHeaderLines = 64
	// ...and at most this many bytes from the start of the file.
	maxHeaderBytes = 8 * 1024
)

// isGenerated reports whether content carries a generated-code header.
//
// Only the file's leading comment block is read (blank lines, a BOM, a
// shebang and Rust `#![...]` attributes are skipped; the first other line
// ends it). Within it, a file is generated if either holds:
//
//   - R1: some line says "do not edit" or "do not modify", and some line has
//     a word beginning "generated", "autogenerated", "auto-generated" or
//     "auto generated" (all case-insensitive). `//go:` directive lines are
//     ignored.
//   - R2: some line has the `@generated` token (see hasGeneratedToken).
func isGenerated(content []byte) bool {
	header := headerLines(content)
	notice, word := false, false
	for _, line := range header {
		if strings.HasPrefix(line, "//go:") {
			continue
		}
		notice = notice || hasDoNotEdit(line)
		word = word || hasGeneratedWord(line)
	}
	if notice && word {
		return true
	}
	for _, line := range header {
		if hasGeneratedToken(line) {
			return true
		}
	}
	return false
}

// headerLines returns the trimmed lines of the file's leading comment block.
func headerLines(content []byte) []string {
	end := len(content)
	if end > maxHeaderBytes {
		end = maxHeaderBytes
		for end > 0 && !utf8.RuneStart(content[end]) {
			end--
		}
	}
	window := strings.TrimPrefix(string(content[:end]), "\uFEFF")
	lines := strings.Split(window, "\n")
	if len(lines) > 0 && lines[len(lines)-1] == "" {
		// A trailing newline ends the last line rather than starting one.
		lines = lines[:len(lines)-1]
	}
	if len(lines) > maxHeaderLines {
		lines = lines[:maxHeaderLines]
	}
	var header []string
	inBlock := false
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if inBlock {
			header = append(header, trimmed)
			inBlock = opensBlock(trimmed, true)
			continue
		}
		switch {
		case trimmed == "" || strings.HasPrefix(trimmed, "#!"):
			// Blank, a shebang or a Rust inner attribute `#![...]`.
			continue
		case strings.HasPrefix(trimmed, "//"):
			header = append(header, trimmed)
		case strings.HasPrefix(trimmed, "/*"):
			header = append(header, trimmed)
			inBlock = opensBlock(trimmed, false)
		case strings.HasPrefix(trimmed, "#") && !strings.HasPrefix(trimmed, "#["):
			header = append(header, trimmed)
		default:
			return header
		}
	}
	return header
}

// opensBlock reports whether a `/* ... */` comment is still open at the end
// of line, given whether one was open at its start.
func opensBlock(line string, openAtStart bool) bool {
	open, close := strings.LastIndex(line, "/*"), strings.LastIndex(line, "*/")
	switch {
	case open >= 0 && close >= 0:
		return open > close
	case open >= 0:
		return true
	case close >= 0:
		return false
	default:
		return openAtStart
	}
}

// normalized is line lower-cased with every whitespace run collapsed to one
// space.
func normalized(line string) string {
	return strings.ToLower(strings.Join(strings.Fields(line), " "))
}

func hasDoNotEdit(line string) bool {
	line = normalized(line)
	return strings.Contains(line, "do not edit") || strings.Contains(line, "do not modify")
}

func isWordRune(r rune) bool {
	return unicode.IsLetter(r) || unicode.IsDigit(r) || r == '_'
}

// hasGeneratedWord reports a word beginning "generated" or "autogenerated";
// "auto-generated" and "auto generated" are covered by the first, whose
// "generated" follows a non-word character.
func hasGeneratedWord(line string) bool {
	line = normalized(line)
	for _, word := range []string{"generated", "autogenerated"} {
		for at := range indexAll(line, word) {
			if r, _ := utf8.DecodeLastRuneInString(line[:at]); at == 0 || !isWordRune(r) {
				return true
			}
		}
	}
	return false
}

// hasGeneratedToken is R2: `@generated`, preceded by line start, whitespace,
// `*`, `/` or `#`, and followed by end of line (optionally `*/`), or by
// whitespace and then `by` or `SignedSource`. Case-sensitive. Not a hit
// inside backticks or quotes (an apostrophe between two letters is not a
// quote).
func hasGeneratedToken(line string) bool {
	const token = "@generated"
	for at := range indexAll(line, token) {
		before, after := line[:at], line[at+len(token):]
		if r, _ := utf8.DecodeLastRuneInString(before); at > 0 && !unicode.IsSpace(r) && r != '*' && r != '/' && r != '#' {
			continue
		}
		rest := strings.TrimLeftFunc(after, unicode.IsSpace)
		ends := rest == "" || rest == "*/"
		first, _ := utf8.DecodeRuneInString(after)
		spaced := after != "" && unicode.IsSpace(first)
		by := false
		if tail, ok := strings.CutPrefix(rest, "by"); ok {
			r, _ := utf8.DecodeRuneInString(tail)
			by = tail == "" || !isWordRune(r)
		}
		if (ends || (spaced && (by || strings.HasPrefix(rest, "SignedSource")))) && !insideQuotes(before) {
			return true
		}
	}
	return false
}

// insideQuotes reports whether before leaves a backtick, double quote or
// single quote open.
func insideQuotes(before string) bool {
	runes := []rune(before)
	for _, quote := range []rune{'`', '"', '\''} {
		count := 0
		for i, r := range runes {
			if r != quote {
				continue
			}
			apostrophe := quote == '\'' && i > 0 && i+1 < len(runes) &&
				(unicode.IsLetter(runes[i-1]) || unicode.IsDigit(runes[i-1])) &&
				(unicode.IsLetter(runes[i+1]) || unicode.IsDigit(runes[i+1]))
			if !apostrophe {
				count++
			}
		}
		if count%2 == 1 {
			return true
		}
	}
	return false
}

// indexAll yields every byte offset of sub in s.
func indexAll(s, sub string) func(func(int) bool) {
	return func(yield func(int) bool) {
		for from := 0; ; {
			at := strings.Index(s[from:], sub)
			if at < 0 {
				return
			}
			if !yield(from + at) {
				return
			}
			from += at + 1
		}
	}
}
