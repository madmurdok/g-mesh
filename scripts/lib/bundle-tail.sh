# shellcheck shell=bash
#
# Shared tail of the plugin bundle scripts (bundle-cargo-plugin.sh,
# bundle-go-plugin.sh): write the installed manifest next to the staged
# binary, then smoke-test the binary. Sourced after scripts/lib/runnable.sh;
# the sourcing script defines `die`, `log` and `host_triple`.

# stage_manifest_and_smoke <language> <display name> <script name> <plugin dir>
#                          <stage dir> <exe name> <target> <marker>
#
# The installed manifest is the checked-in <plugin dir>/plugin.toml with only
# the line <marker> replaced by `command = "./<exe name>"`, so the one place
# [plugin.languages]/[plugin.capabilities]/[plugin.workspace] are declared
# stays the single copy. The directory name must equal the manifest's
# `language` (core/src/plugin_manifest.rs enforces it).
#
# The smoke test needs a binary this host can execute (see runnable.sh); the
# architecture is asserted first so Rosetta cannot run a mislabelled binary.
stage_manifest_and_smoke() {
	local language="$1" display="$2" script="$3" plugin_dir="$4" stage="$5" exe_name="$6" target="$7" marker="$8"

	log "generating $stage/plugin.toml for $exe_name"
	local src_manifest="$plugin_dir/plugin.toml"
	grep -qF "$marker" "$src_manifest" ||
		die "$src_manifest no longer contains '$marker' - update this script's substitution to match its new spelling"

	{
		echo "# Bundled $display plugin manifest, as installed. Generated by"
		echo "# scripts/$script from plugins/$language/plugin.toml - edit that"
		echo "# file, not this one. Only the [plugin.spawn] command line differs from it,"
		echo "# rewritten to name $exe_name, the binary actually staged beside this"
		echo "# manifest for $target."
		echo "#"
		# `[$]`: a literal `$` in the sed pattern, whatever position it is in.
		sed "s#${marker/\$/[\$]}#command = \"./$exe_name\"#" "$src_manifest"
	} >"$stage/plugin.toml"

	grep -qF "command = \"./$exe_name\"" "$stage/plugin.toml" ||
		die "failed to rewrite the command line in the staged manifest"

	local host
	host="$(host_triple)"
	assert_macho_arch "$stage/$exe_name" "$target"
	if can_run_target "$target" "$host"; then
		log "smoke test: handshake with no input"
		local handshake
		handshake="$(printf '' | "$stage/$exe_name" "$REPO_ROOT" 2>/dev/null || true)"
		case "$handshake" in
		*"\"language\":\"$language\""*) log "handshake ok" ;;
		*) die "the staged $display plugin did not produce a handshake (got: ${handshake:-<nothing>})" ;;
		esac
	else
		smoke_skip_or_die "the staged $display plugin's handshake" "$target" "$host"
	fi
}
